// Real-time regression (non-test mode, audio on): inspect card closes with E and stays closed;
// the Coach A → B transition does not freeze the loop.
import { createRequire } from 'node:module';
import { execSync } from 'node:child_process';
const require = createRequire(execSync('npm root -g').toString().trim() + '/');
const { chromium } = require('playwright');
const base = process.argv[2] || 'http://localhost:5173';
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage({ viewport: { width: 640, height: 360 } });
const errors = [];
page.on('console', (m) => m.type() === 'error' && errors.push(m.text().slice(0, 300)));
page.on('pageerror', (e) => errors.push('[pageerror] ' + String(e.stack || e).slice(0, 500)));
await page.goto(`${base}/?preset=low`);
await page.waitForSelector('#title.in', { timeout: 180000 });
await page.evaluate(() => localStorage.setItem('destiny-gate.settings.v1', JSON.stringify({ seenNotice: true })));
await page.reload(); await page.waitForSelector('#title.in', { timeout: 180000 });
await page.hover('button[data-a="settings"]'); await page.click('button[data-a="new"]');
const st = () => page.evaluate(() => ({ ...window.__dg.state(), screen: window.__dg.app.ui.screen?.id || null, frozen: window.__dg.game.player.frozen, audio: window.__dg.app.audio.ctx?.state }));
const until = async (fn, secs, label) => { for (let i = 0; i < secs * 2; i++) { const s = await st(); if (fn(s)) return s; await page.waitForTimeout(500); } console.log('TIMEOUT', label, JSON.stringify(await st())); return null; };
const out = [];
await until((s) => s.app === 'playing' && s.t > 3, 90, 'start');
await page.keyboard.down('KeyW');
await until((s) => s.p[0] > 9.9, 120, 'walk to order');
await page.keyboard.up('KeyW');
await page.waitForTimeout(1500);
await page.evaluate(() => { window.__dg.game.cam.yaw = Math.atan2(10.3 - window.__dg.game.player.pos.x, -0.35 - window.__dg.game.player.pos.z); });
await page.waitForTimeout(600);
await page.keyboard.press('KeyE');
const opened = await until((s) => s.screen === 'inspect', 10, 'inspect open');
out.push(['inspect opens with E', !!opened]);
await page.waitForTimeout(1200);
await page.keyboard.press('KeyE');
await page.waitForTimeout(2500);
let s = await st();
out.push(['inspect closes with E and stays closed', s.screen === null && s.app === 'playing' && !s.frozen]);
await page.evaluate(() => { window.__dg.game.cam.yaw = Math.PI / 2; });
await page.keyboard.down('KeyW');
await until((q) => q.p[0] > 19.3, 150, 'walk to door');
await page.keyboard.press('KeyE');
const through = await until((q) => q.p[0] > 23.6, 150, 'through the doorway');
await page.keyboard.up('KeyW');
out.push(['walked through the door into Coach B (checkpoint 1)', !!through && through.cp === 'cp1']);
const t0 = (await st()).t; await page.waitForTimeout(3000); s = await st();
out.push(['simulation still advancing after the transition', s.t > t0 + 0.2]);
out.push(['audio context running', s.audio === 'running']);
out.push(['no console errors', errors.length === 0]);
for (const [n, ok] of out) console.log(ok ? 'PASS' : 'FAIL', n);
if (errors.length) console.log([...new Set(errors)].slice(0, 8).join('\n'));
await browser.close();
process.exit(out.every((o) => o[1]) ? 0 : 1);

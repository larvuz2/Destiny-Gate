// Real-time UI walkthrough screenshots (non-test mode): title → notice → play → pause → settings.
import { createRequire } from 'node:module';
import { execSync } from 'node:child_process';
const require = createRequire(execSync('npm root -g').toString().trim() + '/');
const { chromium } = require('playwright');
const base = process.argv[2] || 'http://localhost:5173';
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errors = [];
page.on('console', (m) => (m.type() === 'error' || m.type() === 'warning') && errors.push(`[${m.type()}] ${m.text().slice(0, 240)}`));
page.on('pageerror', (e) => errors.push('[pageerror] ' + String(e.stack || e).slice(0, 500)));
const shot = (n) => page.screenshot({ path: `tools/out/ui_${n}.png`, timeout: 120000 });
await page.goto(`${base}/?preset=low`);
await page.waitForSelector('#title.in', { timeout: 180000 });
await page.waitForTimeout(9000);
await shot('1_title');
await page.click('button[data-a="new"]');
await page.waitForTimeout(1500);
await shot('2_notice');
await page.click('button[data-a="go"]');
await page.waitForTimeout(16000);
await shot('3_play');
await page.keyboard.press('Escape');
await page.waitForTimeout(2500);
await shot('4_pause');
await page.click('button[data-a="settings"]').catch(() => {});
await page.waitForTimeout(1500);
await shot('5_settings');
console.log(JSON.stringify(await page.evaluate(() => window.__dg?.state?.())));
if (errors.length) console.log([...new Set(errors)].slice(0, 10).join('\n'));
await browser.close();
